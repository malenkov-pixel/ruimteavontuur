/* =========================================================
   🌍 ОБНОВЛЕНИЕ СТРАНИЦЫ СОЗВЕЗДИЙ
   ========================================================= */

function updateConstellationPage() {

    const language =
        currentLanguage || "ru";

    const data =
        constellationPageTranslations[language] ||
        constellationPageTranslations.ru;


    /* Заголовок */

    const title =
        document.getElementById("constellationTitle");

    if (title) {
        title.textContent =
            data.title;
    }


    /* Подзаголовок */

    const subtitle =
        document.getElementById("constellationSubtitle");

    if (subtitle) {
        subtitle.textContent =
            data.subtitle;
    }


    /* Кнопка назад */

    const back =
        document.getElementById("constellationBack");

    if (back) {
        back.textContent =
            data.back;
    }


    /* Названия созвездий */

    document
        .querySelectorAll(".constellation-card h2")
        .forEach(element => {

            const originalName =
                element.dataset.originalName;

            if (
                originalName &&
                data.names[originalName]
            ) {

                element.textContent =
                    data.names[originalName];

            }

        });


    /* Описания */

    document
        .querySelectorAll(".constellation-description")
        .forEach(element => {

            const originalName =
                element.dataset.originalName;

            if (
                originalName &&
                data.descriptions[originalName]
            ) {

                element.textContent =
                    data.descriptions[originalName];

            }

        });


    /* ALT у изображений */

    document
        .querySelectorAll(".constellation-card")
        .forEach(card => {

            const originalName =
                card.dataset.constellation;

            const image =
                card.querySelector("img");

            if (
                image &&
                originalName &&
                data.names[originalName]
            ) {

                image.alt =
                    data.names[originalName];

            }

        });


    /* Название страницы */

    const pageTitle =
        document.getElementById("pageTitle");

    if (pageTitle) {

        pageTitle.textContent =
            data.title.replace("✨ ", "");

    }


    /* Кнопка языка */

    const languageButton =
        document.getElementById("languageButton");

    if (languageButton) {

        const languageData = {

            ru: {
                image: "images/russia.png",
                text: "Русский"
            },

            kk: {
                image: "images/kazakhstan.png",
                text: "Қазақша"
            },

            cs: {
                image: "images/czechia.png",
                text: "Čeština"
            },

            en: {
                image: "images/usa.png",
                text: "English"
            },

            de: {
                image: "images/germany.png",
                text: "Deutsch"
            },

            fr: {
                image: "images/france.png",
                text: "Français"
            }

        };

        const selected =
            languageData[language] ||
            languageData.ru;


        languageButton.innerHTML = `
            <img
                src="${selected.image}"
                alt="${selected.text}"
            >
            ${selected.text}
        `;

    }

}


/* =========================================================
   🚀 ЗАПУСК
   ========================================================= */

document.addEventListener("DOMContentLoaded", () => {

    const savedLanguage =
        localStorage.getItem("siteLanguage") || "ru";

    currentLanguage = savedLanguage;

    updateConstellationPage();

});